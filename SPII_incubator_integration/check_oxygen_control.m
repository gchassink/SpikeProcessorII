function check_oxygen_control()

global Devices
%disp('check_oxygen_control()');
if isnan(Devices.Incubator.CurrentOxygenTarget)
    return
end

[currentO2,ok] = readParam( ...
    'O2', ...
    Devices.Incubator.AtmowebAddress);

if ~ok
    return
end

margin = ...
    max(0,...
    Devices.Incubator.CurrentOxygenTarget - ...
    (Devices.Incubator.OxygenMax - ...
     Devices.Incubator.MarginPercentage));

if currentO2 + margin < ...
        Devices.Incubator.CurrentOxygenTarget * double(100/105)% asuming 5% CO2 at all times

    sendValveMsg( ...
        'square', ...
        Devices.Incubator.OpenTime, ...
        Devices.Incubator.ValveAddress, ...
        Devices.Incubator.RelayNum);

    disp('Injecting oxygen')
end