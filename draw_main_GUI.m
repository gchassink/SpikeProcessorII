%% draw main GUI
%% 
function  [fig, btn_channel]=draw_main_GUI
   global System FileInfo Devices
   if FileInfo.adaptertype=="Mea2100" %length(FileInfo.channelorder)<70
        XScale=1;YScale=1;
   else
        XScale=1450/1300;YScale=600/500;
   end
    fig=figure('Name','SpikeProcessorII, Main','NumberTitle','off','MenuBar', 'none','ToolBar', 'none','CloseRequestFcn',@callbackExitProgram, 'SelectionType', 'normal', 'Position',[300,300,XScale*1300,YScale*500],'resize','off');
    ax=axes('Parent',fig,'units', 'Pixels', 'Position',[(XScale*1300)-600,50,550,YScale*400]); % determines where data is plotted
    
    % creates all buttons and text for the main interface
    if length(FileInfo.channelorder)<70 && FileInfo.adaptertype~="HDF5 reader" % FileInfo.adaptertype=="Mea2100" || length(FileInfo.channelorder)<70
        xBase=300;yBase=350;
        
        for i=1:8
            for ii=1:8
                index=i*10+ii;
                if index ~= 11 && index ~= 18 && index ~= 81 && index ~= 88 && index ~= 15
                    btn_channel(index) = uicontrol('Parent',fig,'Tag', num2str(index), 'Style', 'pushbutton', 'String', index,...
                        'Position', [i*30+xBase yBase-ii*30 25 25],...
                        'foregroundcolor','white',...
                        'Max', find(FileInfo.channelorder==index),...
                        'Callback', @callbackElectrodeButtons);
    
                end
                
            end
        end
    else
    channel=1; xBase=125*XScale ;   yBase=500;
    for xWell=1:6
        for yWell=1:2
            for yi=1:4
                for xi=1:4
                    index=yi*10+xi;
                    if index ~= 11 && index ~= 14 && index ~= 41 && index ~= 44
                        if channel<=System.ChannelsUsed
                        btn_channel(channel) = uicontrol('Parent',fig,'Tag', num2str(channel), 'Style', 'pushbutton', 'String', channel,...
                            'Position', [xi*21+xBase+(xWell*90) yBase-(yi*21 + yWell*90) 20 20],...
                            'Max', find(FileInfo.channelorder==channel),...
                            'foregroundcolor','white',...
                            'Callback', @callbackElectrodeButtons);
                        
                        channel=channel+1;
                        end
                    end
                end
            end
        end
    end
    for xWell=6:-1:1
        for yWell=3:4
            for yi=1:4
                for xi=1:4
                    index=yi*10+xi;
                    if index ~= 11 && index ~= 14 && index ~= 41 && index ~= 44
                        if channel<=System.ChannelsUsed
                        btn_channel(channel) = uicontrol('Parent',fig,'Tag', num2str(channel), 'Style', 'pushbutton', 'String', channel,...
                            'Position', [xi*21+xBase+(xWell*90) yBase-(yi*21 + yWell*90) 20 20],...
                            'Max', find(FileInfo.channelorder==channel),...
                            'foregroundcolor','white',...
                            'Callback', @callbackElectrodeButtons);
                       
                        channel=channel+1;
                        end
                    end
                end
            end
        end
    end
    end
    show=['rgb'];
    indicatorLabel=["Actual activity", "Average activity", "Noise"];
    for i=1:3
            btn_show(i) = uicontrol('Parent',fig,'UserData', i, 'Style', 'checkbox', 'String', indicatorLabel(i),...
            'Position', [50 YScale*(350-(i+8)*20) 100 20 ],...
            'Value', 1, 'Max', 1,...
            'foregroundcolor',show(i),...
            'Callback', @callbackShowButtonInfo);
    end
    txt_channel = uicontrol('Parent', fig, 'Style', 'text',...
        'String', 'Electrode Selection',...
        'Position', [320 YScale*(500) 100 15]);

    txt_plottype = uicontrol('Parent', fig, 'Style', 'text',...
        'String', 'Plot type:',...
        'HorizontalAlignment','left',...
        'Position', [505 YScale*(427) 100 15]);

    pop_plottype = uicontrol('Style', 'popup',...
        'String', {'None','Rasterplot','Waveforms','Raw data', 'Raw data + detected Spikes', 'Raw well data','AWFR','Stimulus responses','Temperature log', 'Sideband data'},...
        'Position', [505 YScale*(373) 100 50],...
        'Value', 4,...
        'Callback', @callbackSetPlotType);

    btn_dacq = uicontrol('Parent', fig, 'Tag', 'Dacqbtn', 'Style', 'pushbutton',...
        'String', 'Start Dacq',...
        'Position', [275 YScale*(450) 80 40],...
        'Max',2,...
        'Callback', @callbackStartDacq);

    btn_stim = uicontrol('Parent', fig, 'Tag', 'stimbtn', 'Style', 'pushbutton',...
        'String', 'Start Stim.',...
        'Position', [390 YScale*(400) 80 40],...
        'Max',2,...
        'Enable','Off',...
        'Tooltip',sprintf('Start stimulating from file'),...
        'Callback', @callbackStartStimFromList);

    btn_test = uicontrol('Parent', fig, 'Tag', 'testbtn', 'Style', 'pushbutton',...
        'String', 'Start test',...
        'Position', [275 YScale*(400) 80 40],...
        'Max',2,...
        'Enable','on',...
        'Tooltip',sprintf('Start test programs from here'),...
        'Callback', @callbackTestButton);

    btn_rec = uicontrol('Parent', fig, 'Tag', 'Recbtn', 'Style', 'pushbutton',...
        'String', 'Start Recording',...
        'Position', [390 YScale*(450) 80 40],...
        'BackgroundColor','yellow',...
        'Max',3,...
        'Enable','Off',...
        'Callback', @callbackStartRecording);

    txt_rawlength = uicontrol('Parent', fig, 'Style', 'text',...
        'String', 'Raw length:',...
        'HorizontalAlignment','left',...
        'Position', [505 YScale*(448) 80 40]);

    pop_rawlength = uicontrol('Style', 'popup',...
        'String', {'no recording','5 min/hour','10 min/hour', '30 minute/hour', 'continuous'},...
        'Position', [505 YScale*(430) 80 40],...
        'Callback', @callbackRecordRaw);


    txt_detection = uicontrol('Parent', fig, 'Style', 'text',...
        'String', 'Detection Settings',...
        'FontWeight','bold',...
        'HorizontalAlignment','left',...
        'Position', [50 YScale*(390) 150 20]);
   
        
    btn_detect = uicontrol('Parent',fig, 'Style', 'checkbox', 'String', 'Negative Only',...
        'Position', [50 YScale*370 100 20 ],...
        'Value', 1, 'Max', 1,...
        'Callback', @callbackDetectionType);
  

    txt_adapt = uicontrol('Parent', fig, 'Style', 'text',...
        'String', 'Noise Estimation adaptability',...
        'HorizontalAlignment','left',...
        'Tooltip',sprintf('higher is faster, zero means noisevalue is fixed'),...
        'Position', [50 YScale*(345) 150 20]);
    
    sld_adapt = uicontrol('Style', 'slider',...
        'Min',0,'Max',System.max_noise_estimation_entries,'Value',System.max_noise_estimation_entries,...
        'sliderstep', [1/System.max_noise_estimation_entries, 10/System.max_noise_estimation_entries],...
        'Position', [50 YScale*(330) 120 20],...
        'Value',30,...
        'Callback', @callbackNoiseEstimationSpeed);


    txt_adapt_value = uicontrol('Parent', fig, 'Style', 'text', 'tag', 'adaptval',...
        'String', sld_adapt.Value,...
        'Position', [180 YScale*(325) 20 20]);

    txt_thresh = uicontrol('Parent', fig, 'Style', 'text',...
        'String', 'Threshold_multiplier',...
        'HorizontalAlignment','left',...
        'Position', [50 YScale*(305) 150 20]);

    sld_thresh = uicontrol('Style', 'slider',...
        'Min',System.min_threshold_multiplier,'Max',-2,'Value',FileInfo.threshold_multiplier,...
        'sliderstep', [0.5/-System.min_threshold_multiplier, 1/-System.min_threshold_multiplier],...
        'Position', [50 YScale*(290) 120 20],...
        'Callback', @callbackSetThreshold);

    txt_thresh_value = uicontrol('Parent', fig, 'Style', 'text', 'tag', 'threshval',...
        'String', sld_thresh.Value,...
        'Position', [170 YScale*(290) 40 20]);

    txt_frames_buffer = uicontrol('Parent', fig, 'Style', 'text', 'tag', 'framesinbuf',...
        'String', 'Latency: ',...
        'HorizontalAlignment','left',...
        'Position', [50 YScale*(75) 200 20]);
    
    if  isfield (Devices, 'tcxStatus') || isfield (Devices, 'TC02Status')
        txt_temperature = uicontrol('Parent', fig, 'Style', 'text', 'tag', 'temperature',...
            'String', ['Temperature: ' 'no value'],...
            'HorizontalAlignment','left',...
            'Position', [50 YScale*(55) 100 20]);
    end


    txt_time = uicontrol('Parent', fig, 'Style', 'text', 'tag', 'time',...
        'String', 'Total recording time: ',... 
        'HorizontalAlignment','left',...
        'Position', [50 YScale*(450) 200 20]);

    txt_totspikes = uicontrol('Parent', fig, 'Style', 'text', 'tag', 'totspikes',...
        'String', 'Spikes in recording: ',... 
        'HorizontalAlignment','left',...
        'Position', [50 YScale*(430) 200 20]);

    txt_channelnum = uicontrol('Parent', fig, 'Style', 'text', 'tag', 'channelnum',...
        'String', 'Selected electrode: ',... 
        'HorizontalAlignment','left',...
        'Position', [50 YScale*(250) 200 20]);

    txt_estimnoise = uicontrol('Parent', fig, 'Style', 'text', 'tag', 'estimnoise',...
        'String', 'estimated electrode noise: ',... 
        'HorizontalAlignment','left',...
        'Position', [50 YScale*(235) 200 20]);

    txt_chanspikes = uicontrol('Parent', fig, 'Style', 'text', 'tag', 'chanspikes',...
        'String', 'Spikes at electrode: ',...
        'HorizontalAlignment','left',... 
        'Position', [50 YScale*(220) 200 20]);

    txt_chanstim = uicontrol('Parent', fig, 'Style', 'text', 'tag', 'chanstim',...
        'String', 'Next stimulation at electrode: ',...
        'HorizontalAlignment','left',... 
        'Position', [50 YScale*(205) 200 20]);

    txt_stimprecission = uicontrol('Parent', fig, 'Style', 'text', 'tag', 'stimprecission',...
        'String', 'Stimulation precission (ms): ',... 
        'HorizontalAlignment','left',...
        'Position', [50 YScale*(190) 200 20]);



    pause(1); % allow some time to draw
 end